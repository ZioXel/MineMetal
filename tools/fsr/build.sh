#!/bin/bash
# Regenerates native/fsr_shaders.h from easu.frag / rcas.frag.
# Needs ffx_a.h + ffx_fsr1.h (github.com/GPUOpen-Effects/FidelityFX-FSR, ffx-fsr/) in this folder, glslangValidator and spirv-cross.
set -e
cd "$(dirname "$0")"
for s in easu rcas; do
  glslangValidator -V --target-env vulkan1.1 -S frag $s.frag -o /tmp/$s.spv >/dev/null
  spirv-cross /tmp/$s.spv --msl --msl-version 20300 --rename-entry-point main main_$s frag --output /tmp/$s.metal
done
python3 - <<'PY'
import json
out = ['// Generated by tools/fsr/build.sh: AMD FidelityFX Super Resolution 1.0 (EASU + RCAS), 32-bit path, as MSL.',
'// FSR: Copyright (c) 2021 Advanced Micro Devices, Inc. MIT licensed (see tools/fsr/LICENSE-FSR.txt).', '#pragma once', '']
for name, f in (('MM_FSR_EASU_MSL', '/tmp/easu.metal'), ('MM_FSR_RCAS_MSL', '/tmp/rcas.metal')):
    out.append('static const char *%s =' % name)
    out += ['    ' + json.dumps(l + '\n') for l in open(f).read().splitlines()]
    out += [';', '']
open('../../native/fsr_shaders.h', 'w').write('\n'.join(out))
PY
